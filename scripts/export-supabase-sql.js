const { db, initDb } = require('../db');
const fs = require('fs');
const path = require('path');

async function exportSupabaseSql() {
  await initDb();

  let sql = `-- ==========================================
-- BioLink Schema & Data Export for Supabase SQL Editor
-- Target Database: PostgreSQL (Supabase)
-- Generated on: ${new Date().toISOString()}
-- ==========================================

-- Enable UUID extension (optional, for utility)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Drop existing tables in reverse dependency order
DROP TABLE IF EXISTS "clicks" CASCADE;
DROP TABLE IF EXISTS "views" CASCADE;
DROP TABLE IF EXISTS "domains" CASCADE;
DROP TABLE IF EXISTS "video" CASCADE;
DROP TABLE IF EXISTS "music" CASCADE;
DROP TABLE IF EXISTS "gallery" CASCADE;
DROP TABLE IF EXISTS "links" CASCADE;
DROP TABLE IF EXISTS "bios" CASCADE;
DROP TABLE IF EXISTS "settings" CASCADE;
DROP TABLE IF EXISTS "users" CASCADE;

-- 1. USERS TABLE
CREATE TABLE "users" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "username" VARCHAR(255) UNIQUE NOT NULL,
    "email" VARCHAR(255) UNIQUE NOT NULL,
    "password" TEXT NOT NULL,
    "role" VARCHAR(50) DEFAULT 'user' CHECK ("role" IN ('user', 'admin', 'mod')),
    "displayName" VARCHAR(255),
    "avatarUrl" TEXT,
    "oauthProvider" VARCHAR(50),
    "oauthId" VARCHAR(255),
    "suspended" INT DEFAULT 0,
    "createdAt" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. BIOS TABLE
CREATE TABLE "bios" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId" BIGINT NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
    "username" VARCHAR(255) UNIQUE NOT NULL,
    "displayName" VARCHAR(255),
    "tagline" TEXT,
    "bio" TEXT,
    "pronouns" VARCHAR(100),
    "avatarUrl" TEXT,
    "theme" VARCHAR(100) DEFAULT 'dark',
    "accentColor" VARCHAR(50) DEFAULT '#7c6aff',
    "btnStyle" VARCHAR(50) DEFAULT 'pill',
    "location" VARCHAR(255),
    "showViews" INT DEFAULT 1,
    "published" INT DEFAULT 1,
    "customDomain" VARCHAR(255),
    "domainVerified" INT DEFAULT 0,
    "domainToken" TEXT,
    "bgType" VARCHAR(50) DEFAULT 'gradient',
    "bgValue" TEXT,
    "particlesEnabled" INT DEFAULT 0,
    "cursorTrail" INT DEFAULT 0,
    "snowEnabled" INT DEFAULT 0,
    "bgVideo" TEXT,
    "customCSS" TEXT,
    "audioUrl" TEXT,
    "socials" JSONB DEFAULT '{}'::jsonb,
    "seoTitle" VARCHAR(255),
    "seoDesc" TEXT,
    "seoImage" TEXT,
    "updatedAt" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 3. LINKS TABLE
CREATE TABLE "links" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId" BIGINT NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
    "title" VARCHAR(255) NOT NULL,
    "url" TEXT NOT NULL,
    "description" TEXT,
    "icon" VARCHAR(100),
    "tag" VARCHAR(100),
    "password" VARCHAR(255),
    "sortOrder" INT DEFAULT 0,
    "active" INT DEFAULT 1
);

-- 4. GALLERY TABLE
CREATE TABLE "gallery" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId" BIGINT NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
    "imageUrl" TEXT NOT NULL,
    "caption" TEXT,
    "sortOrder" INT DEFAULT 0
);

-- 5. MUSIC TABLE
CREATE TABLE "music" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId" BIGINT NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
    "type" VARCHAR(50) NOT NULL CHECK ("type" IN ('spotify', 'soundcloud')),
    "url" TEXT NOT NULL,
    "autoplay" INT DEFAULT 0
);

-- 6. VIDEO TABLE
CREATE TABLE "video" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId" BIGINT NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
    "type" VARCHAR(50) NOT NULL CHECK ("type" IN ('youtube', 'vimeo', 'mp4')),
    "url" TEXT NOT NULL,
    "title" VARCHAR(255)
);

-- 7. VIEWS TABLE
CREATE TABLE "views" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId" BIGINT NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
    "date" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    "ip" VARCHAR(100),
    "referrer" TEXT
);

-- 8. CLICKS TABLE
CREATE TABLE "clicks" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "linkId" BIGINT NOT NULL REFERENCES "links"("id") ON DELETE CASCADE,
    "date" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    "ip" VARCHAR(100)
);

-- 9. SETTINGS TABLE
CREATE TABLE "settings" (
    "id" INT PRIMARY KEY CHECK ("id" = 1),
    "platformName" VARCHAR(255) DEFAULT 'BioLink',
    "allowRegister" INT DEFAULT 1,
    "showViews" INT DEFAULT 1,
    "maintenance" INT DEFAULT 0
);

-- 10. DOMAINS TABLE
CREATE TABLE "domains" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId" BIGINT NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
    "domain" VARCHAR(255) NOT NULL,
    "verified" INT DEFAULT 0,
    "createdAt" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- SEED / EXISTING DATA INSERTS
-- ==========================================

`;

  const tables = ['users', 'bios', 'links', 'gallery', 'music', 'video', 'views', 'clicks', 'settings', 'domains'];

  for (const tbl of tables) {
    await new Promise((resolve) => {
      db.all(`SELECT * FROM ${tbl}`, [], (err, rows) => {
        if (!err && rows && rows.length > 0) {
          sql += `-- Data for table: ${tbl}\n`;
          for (const row of rows) {
            const keys = Object.keys(row);
            const cols = keys.map(k => `"${k}"`).join(', ');
            const vals = keys.map(k => {
              const val = row[k];
              if (val === null || val === undefined) return 'NULL';
              if (typeof val === 'number') return val;
              if (typeof val === 'boolean') return val ? 'TRUE' : 'FALSE';
              if (k === 'socials' && typeof val === 'string' && (val.startsWith('{') || val.startsWith('['))) {
                return `'${val.replace(/'/g, "''")}'::jsonb`;
              }
              return `'${String(val).replace(/'/g, "''")}'`;
            }).join(', ');
            sql += `INSERT INTO "${tbl}" (${cols}) VALUES (${vals}) ON CONFLICT DO NOTHING;\n`;
          }
          sql += `\n`;
        }
        resolve();
      });
    });
  }

  // Reset sequences to maximum ID for auto-incrementing identity columns
  sql += `-- Reset primary key sequences for PostgreSQL identity columns\n`;
  for (const tbl of ['users', 'bios', 'links', 'gallery', 'music', 'video', 'views', 'clicks', 'domains']) {
    sql += `SELECT setval(pg_get_serial_sequence('"${tbl}"', 'id'), COALESCE((SELECT MAX("id") FROM "${tbl}"), 1), true);\n`;
  }

  const outputPath = path.join(__dirname, '..', 'supabase_schema_and_data.sql');
  fs.writeFileSync(outputPath, sql);
  console.log(`Supabase SQL script regenerated successfully at: ${outputPath}`);
}

exportSupabaseSql().catch(console.error);
